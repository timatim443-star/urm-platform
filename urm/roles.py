"""Роли и права. Единственное место, где настраивается доступ.

Чтобы изменить, что видит роль, — правьте этот словарь и перезапустите
приложение. Код страниц трогать не нужно.

Поля роли:
  title            — подпись в интерфейсе;
  all_labs         — True: видит все лаборатории (города);
                     False: только перечисленные у пользователя в app_user.labs;
  pages            — какие страницы доступны (идентификаторы — см. PAGES);
  network_quality  — видит ли сетевую диагностику качества
                     (покрытие, конфликты, воронку, проблемы подготовки).
                     У этих витрин нет разреза по лабораториям, поэтому
                     городской роли они по умолчанию не показываются;
  mapping_edit     — может ли сохранять изменения маппинга в базу;
  users_manage     — может ли заводить пользователей и менять им роли
                     (страница «12 Пользователи»);
  single_session   — True: учётка открыта только на одном устройстве — новый вход
                     закрывает прежний. False: одной учёткой могут пользоваться
                     сразу несколько человек (общая учётка города);
  own_password     — может ли сам сменить свой пароль в меню профиля. У общих
                     учёток выключено: один человек сменил бы пароль всем остальным.
                     Пароль общей учётки меняет администратор на «12 Пользователи».

Сохранение в базу (маппинг, пользователи, смена пароля) дополнительно требует
учётной записи на запись URM_RW_USER — без неё всё открывается только на просмотр.

В витринах одна лаборатория = один город (одна информационная база на город),
поэтому доступ задаётся списком лабораторий.
"""
from __future__ import annotations

# Порядок здесь = порядок в меню. Подписи совпадают с вкладками генератора отчётов.
PAGES: dict[str, str] = {
    "method": "00 Методика",  # главная страница: открывается первой
    "overview": "01 Общая ситуация",
    "labs": "02 Города / лаборатории",
    "customers": "03 Заказчики",
    "customer_card": "04 Карточка заказчика",
    "materials": "05 Расходные материалы",
    "procedure": "06 Процедурные кабинеты",
    "anomalies": "07 Аномалии",
    "quality": "08 Качество данных",
    "watchlist": "09 К отработке",
    "mapping": "11 Маппинг",
    "users": "12 Пользователи",
}

ADMIN_PAGES = ("mapping", "users")
REPORT_PAGES = [p for p in PAGES if p not in ADMIN_PAGES]

ROLES: dict[str, dict] = {
    # 1. Обычный аккаунт: данные только своего города.
    "city": {
        "title": "Город",
        "all_labs": False,
        "pages": REPORT_PAGES,
        "network_quality": False,
        "mapping_edit": False,
        "users_manage": False,
        "single_session": False,
        "own_password": False,
    },
    # 2. Все города, без маппинга.
    "network": {
        "title": "Все города",
        "all_labs": True,
        "pages": REPORT_PAGES,
        "network_quality": True,
        "mapping_edit": False,
        "users_manage": False,
        "single_session": False,
        "own_password": False,
    },
    # 3. Администратор: всё, включая правку маппинга и пользователей.
    "admin": {
        "title": "Администратор",
        "all_labs": True,
        "pages": list(PAGES),
        "network_quality": True,
        "mapping_edit": True,
        "users_manage": True,
        "single_session": True,
        "own_password": True,
    },
}


def policy(role: str) -> dict:
    return ROLES.get(role, ROLES["city"])
