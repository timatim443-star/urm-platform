def _kinds() -> set[str]:
    raw = os.environ.get("URM_UI_SHOW")
    if raw is None:
        return {"tech", "notice", "hint"}
    return {part.strip() for part in raw.split(",") if part.strip()}


def _hidden() -> set[str]:
    return {part.strip() for part in os.environ.get("URM_UI_HIDE", "").split(",") if part.strip()}


def enabled(notice_id: str) -> bool:
    kind = TEXTS[notice_id][0]
    if kind == "test":
        return True  # показывается, пока включён тестовый режим
    return kind in _kinds() and notice_id not in _hidden()


def text(notice_id: str, **values) -> str | None:
    """Текст надписи или None, если она отключена. Для help= у полей ввода."""
    if not enabled(notice_id):
        return None
    body = TEXTS[notice_id][1]
    return body.format(**values) if values else body


def show(notice_id: str, **values) -> None:
    """Плашка-пояснение в стиле генератора отчётов."""
    body = text(notice_id, **values)
    if body:
        html(f'<div class="notice">{body}</div>')
